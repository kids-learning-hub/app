/* ═══════════════════════════════════════════════════════════════════════
   Kids Learning Hub — browser-game guides + language copies
   ═══════════════════════════════════════════════════════════════════════
   Usage (from apps-site/):

     node tools/build-games.js        (build-all.js runs it after build-langs)

   For every game listed in tools/games-data-*.js:

   1. Injects a guide block (intro, tips for parents, FAQ) into the English
      page play/<slug>.html, between the markers below, just before the app
      call-to-action. Re-running replaces the block.

   2. Emits play/<lang>/<slug>.html for fr, es and ar with their own title,
      description, canonical, hreflang set, lang/dir and localised guide —
      the same approach as tools/build-worksheets.js.

   3. Points the fr/es/ar games hubs (play/<lang>/index.html, written by
      build-langs.js) at the localised game pages, and refreshes the
      <!--GAMEPAGES--> block of sitemap.xml.

   Game pages must use absolute links (/logos/…, /play/play.js…) because the
   copies live one folder deeper.
   ═══════════════════════════════════════════════════════════════════════ */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PLAY = path.join(ROOT, 'play');
const BASE = 'https://kids-learning-hub.cc';
const LANGS = ['en', 'fr', 'es', 'ar'];
const DIR = { en: 'ltr', fr: 'ltr', es: 'ltr', ar: 'rtl' };

const GAMES = [
  ...require('./games-data-math.js'),
  ...require('./games-data-logic.js'),
  ...require('./games-data-world.js'),
];

const BEGIN = '<!-- GAME_GUIDE auto-generated by tools/build-games.js — edit tools/games-data-*.js -->';
const END = '<!-- /GAME_GUIDE -->';

const UI = {
  en: { about: 'About this game', how: 'Tips for parents and teachers', faq: 'Frequently asked questions', ages: 'Best for ages', home: 'Home', games: 'Games' },
  fr: { about: 'À propos de ce jeu', how: 'Conseils pour les parents et les enseignants', faq: 'Questions fréquentes', ages: 'Conseillé de', home: 'Accueil', games: 'Jeux' },
  es: { about: 'Sobre este juego', how: 'Consejos para familias y docentes', faq: 'Preguntas frecuentes', ages: 'Recomendado de', home: 'Inicio', games: 'Juegos' },
  ar: { about: 'عن هذه اللعبة', how: 'نصائح للآباء والمعلّمين', faq: 'أسئلة شائعة', ages: 'الأنسب لأعمار', home: 'الرئيسية', games: 'الألعاب' },
};

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const urlOf = (slug, lang) => `${BASE}/play/${lang === 'en' ? '' : lang + '/'}${slug}.html`;
const reEsc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function guideBlock(g, lang) {
  const t = UI[lang];
  return `${BEGIN}
  <section class="ws-guide" dir="${DIR[lang]}">
    <h2>${g.emoji} ${t.about}</h2>
    <p class="ws-lede">${esc(g.lede[lang])}</p>
    <p class="ws-ages"><span aria-hidden="true">${g.emoji}</span> ${t.ages} <strong>${g.ages}</strong></p>

    <h2>${t.how}</h2>
    <ul class="ws-tips">
${g.how[lang].map(li => `      <li>${esc(li)}</li>`).join('\n')}
    </ul>

    <h2>${t.faq}</h2>
${g.faq[lang].map(([q, a]) => `    <details class="faq"><summary>${esc(q)}</summary><p>${esc(a)}</p></details>`).join('\n')}
  </section>
${END}`;
}

function schemaFor(g, lang) {
  const t = UI[lang];
  const name = g.meta[lang].title.split(/\s*[|—(]/)[0].trim();
  return [
    { '@context': 'https://schema.org', '@type': 'FAQPage', inLanguage: lang,
      mainEntity: g.faq[lang].map(([q, a]) => ({ '@type': 'Question', name: q, acceptedAnswer: { '@type': 'Answer', text: a } })) },
    { '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: [
      { '@type': 'ListItem', position: 1, name: t.home, item: BASE + (lang === 'en' ? '/' : `/${lang}/`) },
      { '@type': 'ListItem', position: 2, name: t.games, item: `${BASE}/play/${lang === 'en' ? '' : lang + '/'}` },
      { '@type': 'ListItem', position: 3, name, item: urlOf(g.slug, lang) }] },
  ].map(o => `<script type="application/ld+json" data-gen="games">\n${JSON.stringify(o)}\n</script>`).join('\n');
}

const upsert = (html, re, tag) => re.test(html) ? html.replace(re, tag) : html.replace('</head>', tag + '\n</head>');

let written = 0;
const problems = [];

for (const g of GAMES) {
  const src = path.join(PLAY, g.slug + '.html');
  if (!fs.existsSync(src)) { problems.push(`${g.slug}: no play/${g.slug}.html`); continue; }
  const original = fs.readFileSync(src, 'utf8');
  const rel = [...original.matchAll(/(?:href|src)="((?!https?:|\/\/|#|mailto:|data:|\/|\$\{|\?)[^"]+)"/g)].map(m => m[1]);
  if (rel.length) { problems.push(`${g.slug}.html has relative refs: ${[...new Set(rel)].slice(0, 4).join(', ')}`); continue; }

  for (const lang of LANGS) {
    let html = original;
    const block = guideBlock(g, lang);
    if (html.includes(BEGIN)) html = html.replace(new RegExp(reEsc(BEGIN) + '[\\s\\S]*?' + reEsc(END)), block);
    else if (html.includes('<div class="appcta"')) html = html.replace('<div class="appcta"', block + '\n\n  <div class="appcta"');
    else html = html.replace('<div class="ad-slot"', block + '\n\n  <div class="ad-slot"');

    html = html.replace(/<html[^>]*>/, `<html lang="${lang}" dir="${DIR[lang]}">`);
    const m = g.meta[lang];
    html = html.replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(m.title)}</title>`);
    html = upsert(html, /<meta name="description" content="[^"]*"\s*\/?>/, `<meta name="description" content="${esc(m.desc)}" />`);
    html = upsert(html, /<meta property="og:title" content="[^"]*"\s*\/?>/, `<meta property="og:title" content="${esc(m.title)}" />`);
    html = upsert(html, /<meta property="og:description" content="[^"]*"\s*\/?>/, `<meta property="og:description" content="${esc(m.desc)}" />`);
    html = upsert(html, /<link rel="canonical"[^>]*>/, `<link rel="canonical" href="${urlOf(g.slug, lang)}" />`);
    html = upsert(html, /<meta property="og:url" content="[^"]*"\s*\/?>/, `<meta property="og:url" content="${urlOf(g.slug, lang)}" />`);
    html = html.replace(/<link rel="alternate" hreflang="[^"]*"[^>]*>\n?/g, '');
    html = html.replace('<link rel="canonical"',
      LANGS.map(l => `<link rel="alternate" hreflang="${l}" href="${urlOf(g.slug, l)}" />`).join('\n') +
      `\n<link rel="alternate" hreflang="x-default" href="${urlOf(g.slug, 'en')}" />\n<link rel="canonical"`);
    html = html.replace(/<script type="application\/ld\+json" data-gen="games">[\s\S]*?<\/script>\n?/g, '');
    html = html.replace('</head>', schemaFor(g, lang) + '\n</head>');

    if (lang !== 'en') {
      /* crumbs/footer: home and games hub in the same language */
      html = html.replace(/href="\/play\/"/g, `href="/play/${lang}/"`).replace(/href="\/"/g, `href="/${lang}/"`);
      html = html.replace('</head>',
        `<script>try{localStorage.setItem('vsm_lang',${JSON.stringify(lang)})}catch(e){}` +
        `document.documentElement.lang=${JSON.stringify(lang)};document.documentElement.dir=${JSON.stringify(DIR[lang])};</script>\n</head>`);
    }
    const out = lang === 'en' ? src : path.join(PLAY, lang, g.slug + '.html');
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, html, 'utf8');
    written++;
  }
}

if (problems.length) { console.error('✗ aborted:\n  - ' + problems.join('\n  - ')); process.exit(1); }

/* fr/es/ar hubs → localised game pages */
for (const lang of LANGS.filter(l => l !== 'en')) {
  const hub = path.join(PLAY, lang, 'index.html');
  if (!fs.existsSync(hub)) continue;
  let h = fs.readFileSync(hub, 'utf8');
  for (const g of GAMES) h = h.split(`href="/play/${g.slug}.html"`).join(`href="/play/${lang}/${g.slug}.html"`);
  fs.writeFileSync(hub, h, 'utf8');
}

/* sitemap */
const smPath = path.join(ROOT, 'sitemap.xml');
let sm = fs.readFileSync(smPath, 'utf8');
const today = new Date().toISOString().slice(0, 10);
const block = GAMES.map(g => {
  const alts = LANGS.map(l => `    <xhtml:link rel="alternate" hreflang="${l}" href="${urlOf(g.slug, l)}"/>`).join('\n');
  return LANGS.map(l => `  <url>
    <loc>${urlOf(g.slug, l)}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.7</priority>
${alts}
    <xhtml:link rel="alternate" hreflang="x-default" href="${urlOf(g.slug, 'en')}"/>
  </url>`).join('\n');
}).join('\n');
const marker = /<!--GAMEPAGES-->[\s\S]*?<!--\/GAMEPAGES-->/;
const payload = `<!--GAMEPAGES-->\n${block}\n  <!--/GAMEPAGES-->`;
sm = marker.test(sm) ? sm.replace(marker, payload) : sm.replace(/<\/urlset>/, `  ${payload}\n</urlset>`);
for (const g of GAMES) {
  const dup = new RegExp(`  <url>\\s*<loc>${reEsc(urlOf(g.slug, 'en'))}</loc>(?![\\s\\S]{0,200}xhtml:link)[\\s\\S]*?</url>\\n`, 'g');
  sm = sm.replace(dup, '');
}
fs.writeFileSync(smPath, sm, 'utf8');

console.log(`✓ ${written} game pages written (${GAMES.length} games × ${LANGS.length} languages)`);
console.log('✓ play/fr|es|ar hubs linked to localised games; sitemap.xml <!--GAMEPAGES--> refreshed');
