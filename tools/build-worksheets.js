/* ═══════════════════════════════════════════════════════════════════════
   Kids Learning Hub — worksheet page content + language variants
   ═══════════════════════════════════════════════════════════════════════
   Usage (from apps-site/):

     node tools/build-worksheets.js

   Does two things for every topic listed in tools/worksheets-data.js:

   1. Injects a content block (intro, teaching notes, FAQ) into the English
      page, between the markers below. Re-running replaces the block, so
      the file is safe to regenerate and safe to hand-edit around.

   2. Emits /worksheets/<lang>/<slug>.html for fr, es and ar, each with its
      own canonical, hreflang set, lang/dir and localised content — the
      same approach build-langs.js uses for the section pages.

   Adds FAQPage + BreadcrumbList schema to every page.

   Topics with no entry in worksheets-data.js are left untouched.
   ═══════════════════════════════════════════════════════════════════════ */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const WS = path.join(ROOT, 'worksheets');
const BASE = 'https://kids-learning-hub.cc';
const LANGS = ['en', 'fr', 'es', 'ar'];
const DIR = { en: 'ltr', fr: 'ltr', es: 'ltr', ar: 'rtl' };

const TOPICS = require('./worksheets-data.js');

const BEGIN = '<!-- WS_CONTENT auto-generated by tools/build-worksheets.js — edit tools/worksheets-data.js -->';
const END = '<!-- /WS_CONTENT -->';

const UI = {
  en: { how: 'How to get the most from these sheets', faq: 'Frequently asked questions',
        ages: 'Best for ages', home: 'Home', ws: 'Worksheets', more: 'More worksheets' },
  fr: { how: 'Comment tirer le meilleur de ces fiches', faq: 'Questions fréquentes',
        ages: 'Conseillé de', home: 'Accueil', ws: 'Fiches', more: "Plus de fiches" },
  es: { how: 'Cómo aprovechar mejor estas fichas', faq: 'Preguntas frecuentes',
        ages: 'Recomendado de', home: 'Inicio', ws: 'Fichas', more: 'Más fichas' },
  ar: { how: 'كيف تستفيد أكثر من هذه الأوراق', faq: 'أسئلة شائعة',
        ages: 'الأنسب لأعمار', home: 'الرئيسية', ws: 'أوراق العمل', more: 'أوراق عمل أخرى' },
};

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;')
  .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const urlOf = (slug, lang) =>
  `${BASE}/worksheets/${lang === 'en' ? '' : lang + '/'}${slug}.html`;

function contentBlock(topic, lang) {
  const t = UI[lang];
  const how = topic.how[lang].map(li => `      <li>${esc(li)}</li>`).join('\n');
  const faq = topic.faq[lang].map(([q, a]) =>
    `    <details class="faq"><summary>${esc(q)}</summary><p>${esc(a)}</p></details>`).join('\n');
  return `${BEGIN}
  <section class="ws-guide">
    <p class="ws-lede">${esc(topic.lede[lang])}</p>
    <p class="ws-ages"><span aria-hidden="true">${topic.emoji}</span> ${t.ages} <strong>${topic.ages}</strong></p>

    <h2>${t.how}</h2>
    <ul class="ws-tips">
${how}
    </ul>

    <h2>${t.faq}</h2>
${faq}
  </section>
${END}`;
}

function schemaFor(topic, lang) {
  const t = UI[lang];
  /* Breadcrumbs surface in search results, so the last crumb must read as a
     title ("Word tracing"), not as the internal slug ("words"). Take the part
     of the localised title before the first separator. */
  const crumbName = (topic.meta && topic.meta[lang] && topic.meta[lang].title)
    ? topic.meta[lang].title.split(/\s*[|(]/)[0].trim()
    : topic.slug;
  return [
    { '@context': 'https://schema.org', '@type': 'FAQPage', inLanguage: lang,
      mainEntity: topic.faq[lang].map(([q, a]) => ({
        '@type': 'Question', name: q,
        acceptedAnswer: { '@type': 'Answer', text: a } })) },
    { '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: [
      { '@type': 'ListItem', position: 1, name: t.home, item: BASE + '/' },
      { '@type': 'ListItem', position: 2, name: t.ws,
        item: `${BASE}/worksheets/${lang === 'en' ? '' : lang + '/'}` },
      { '@type': 'ListItem', position: 3, name: crumbName, item: urlOf(topic.slug, lang) }] },
  ].map(o => `<script type="application/ld+json">\n${JSON.stringify(o)}\n</script>`).join('\n');
}

function hreflangBlock(slug) {
  let out = '';
  for (const l of LANGS) out += `<link rel="alternate" hreflang="${l}" href="${urlOf(slug, l)}" />\n`;
  out += `<link rel="alternate" hreflang="x-default" href="${urlOf(slug, 'en')}" />\n`;
  return out;
}

/* Replace an existing tag, else insert before </head>. */
const upsert = (html, re, tag) =>
  re.test(html) ? html.replace(re, tag) : html.replace('</head>', tag + '\n</head>');

let written = 0, skipped = [], problems = [];

for (const topic of TOPICS) {
  const srcPath = path.join(WS, topic.slug + '.html');
  if (!fs.existsSync(srcPath)) { skipped.push(`${topic.slug} (no such worksheet page)`); continue; }
  let original = fs.readFileSync(srcPath, 'utf8');

  /* Language copies live one level deeper, so relative refs would break. */
  const rel = [...original.matchAll(/(?:href|src)="((?!https?:|\/\/|#|mailto:|data:|\/|\$\{|\?)[^"]+)"/g)]
    .map(m => m[1]);
  if (rel.length) {
    problems.push(`${topic.slug}.html: ${rel.length} relative ref(s) — convert to absolute first ` +
                  `(${[...new Set(rel)].slice(0, 4).join(', ')})`);
    continue;
  }

  for (const lang of LANGS) {
    let html = original;

    /* content block: replace if present, else insert before the app CTA
       (which sits after the sheet), else before the footer. */
    const block = contentBlock(topic, lang);
    if (html.includes(BEGIN)) {
      html = html.replace(new RegExp(BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') +
        '[\\s\\S]*?' + END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')), block);
    } else if (html.includes('<div class="appcta"')) {
      html = html.replace('<div class="appcta"', block + '\n\n  <div class="appcta"');
    } else {
      html = html.replace('<footer', block + '\n\n<footer');
    }

    html = html.replace(/<html[^>]*>/, `<html lang="${lang}" dir="${DIR[lang]}">`);

    /* Localised title + description. Without these the fr/es/ar copies would
       carry the English title, which makes them near-duplicates and stops
       them ranking for the queries they exist to serve. */
    const m = topic.meta && topic.meta[lang];
    if (m) {
      html = html.replace(/<title>[\s\S]*?<\/title>/, `<title>${esc(m.title)}</title>`);
      html = upsert(html, /<meta name="description" content="[^"]*"\s*\/?>/,
        `<meta name="description" content="${esc(m.desc)}" />`);
      html = upsert(html, /<meta property="og:title" content="[^"]*"\s*\/?>/,
        `<meta property="og:title" content="${esc(m.title)}" />`);
      html = upsert(html, /<meta property="og:description" content="[^"]*"\s*\/?>/,
        `<meta property="og:description" content="${esc(m.desc)}" />`);
      html = upsert(html, /<meta property="og:locale" content="[^"]*"\s*\/?>/,
        `<meta property="og:locale" content="${lang}" />`);
    }

    html = upsert(html, /<link rel="canonical"[^>]*>/,
      `<link rel="canonical" href="${urlOf(topic.slug, lang)}" />`);
    html = html.replace(/<link rel="alternate" hreflang="[^"]*"[^>]*>\n?/g, '');
    html = html.replace('<link rel="canonical"', hreflangBlock(topic.slug) + '<link rel="canonical"');
    html = upsert(html, /<meta property="og:url" content="[^"]*"\s*\/?>/,
      `<meta property="og:url" content="${urlOf(topic.slug, lang)}" />`);

    /* schema: strip any previously generated pair, then append */
    html = html.replace(/<script type="application\/ld\+json">\n\{"@context":"https:\/\/schema\.org","@type":"(?:FAQPage|BreadcrumbList)[\s\S]*?<\/script>\n?/g, '');
    html = html.replace('</head>', schemaFor(topic, lang) + '\n</head>');

    if (lang !== 'en') {
      html = html.replace('</head>',
        `<script>try{localStorage.setItem('vsm_lang',${JSON.stringify(lang)})}catch(e){}` +
        `document.documentElement.lang=${JSON.stringify(lang)};` +
        `document.documentElement.dir=${JSON.stringify(DIR[lang])};</script>\n</head>`);
    }

    const outPath = lang === 'en' ? srcPath : path.join(WS, lang, topic.slug + '.html');
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, html, 'utf8');
    written++;
  }
}

/* ── sitemap ──────────────────────────────────────────────────────────── */
if (problems.length) {
  console.error('✗ aborted:\n  - ' + problems.join('\n  - '));
  process.exit(1);
}

const smPath = path.join(ROOT, 'sitemap.xml');
let sm = fs.readFileSync(smPath, 'utf8');
const today = new Date().toISOString().slice(0, 10);

const block = TOPICS.filter(t => fs.existsSync(path.join(WS, t.slug + '.html'))).map(topic => {
  const alts = LANGS.map(l =>
    `    <xhtml:link rel="alternate" hreflang="${l}" href="${urlOf(topic.slug, l)}"/>`).join('\n');
  return LANGS.map(l => `  <url>
    <loc>${urlOf(topic.slug, l)}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.7</priority>
${alts}
    <xhtml:link rel="alternate" hreflang="x-default" href="${urlOf(topic.slug, 'en')}"/>
  </url>`).join('\n');
}).join('\n');

const marker = /<!--WSPAGES-->[\s\S]*?<!--\/WSPAGES-->/;
const payload = `<!--WSPAGES-->\n${block}\n  <!--/WSPAGES-->`;
sm = marker.test(sm) ? sm.replace(marker, payload)
                     : sm.replace(/<\/urlset>/, `  ${payload}\n</urlset>`);

/* remove the plain single-language entries now superseded above */
for (const topic of TOPICS) {
  const dup = new RegExp(
    `  <url>\\s*<loc>${urlOf(topic.slug, 'en').replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}</loc>` +
    `(?![\\s\\S]{0,200}xhtml:link)[\\s\\S]*?</url>\\n`, 'g');
  sm = sm.replace(dup, '');
}
fs.writeFileSync(smPath, sm, 'utf8');

console.log(`✓ ${written} worksheet pages written (${TOPICS.length} topics × ${LANGS.length} languages)`);
if (skipped.length) console.log('  skipped: ' + skipped.join(', '));
console.log('✓ sitemap.xml <!--WSPAGES--> block refreshed');
